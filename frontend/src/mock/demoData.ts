import type { DiscoveredSession, ProcessInfo, ScanMeta, SystemMetrics, Task } from '../types'

const now = Date.now()

function iso(minutesAgo: number): string {
  return new Date(now - minutesAgo * 60_000).toISOString()
}

function proc(pid: number, name: string, cwd: string, cmdline: string[]): ProcessInfo {
  return {
    pid,
    ppid: Math.max(1, pid - 1),
    name,
    cmdline,
    cwd,
    user: 'demo',
    tty: 'pts/4',
    status: 'running',
    cpu_percent: 2.4,
    memory_percent: 1.2,
    create_time: Math.floor((now - 3_600_000) / 1000),
    elapsed: '1h0m',
    children: [],
  }
}

function session(partial: Partial<DiscoveredSession> & Pick<DiscoveredSession, 'session_id' | 'agent_type' | 'project' | 'cwd' | 'status' | 'status_group' | 'status_dot' | 'current_activity'>): DiscoveredSession {
  const rootPid = partial.root_pid ?? Math.floor(10_000 + Math.random() * 20_000)
  const projectName = partial.project
  const cwd = partial.cwd
  return {
    session_id: partial.session_id,
    project_key: partial.project_key || projectName.toLowerCase().replace(/\s+/g, '-'),
    cwd,
    root_process: partial.root_process || proc(rootPid, partial.agent_type, cwd, [partial.agent_type, 'demo']),
    all_pids: partial.all_pids || [rootPid],
    agent_type: partial.agent_type,
    agent_confidence: partial.agent_confidence ?? 0.96,
    agent_detection_reason: 'demo data',
    agent_detection_evidence: [partial.agent_type],
    root_pid: rootPid,
    root_cmd: partial.root_cmd || `${partial.agent_type} demo`,
    user: 'demo',
    tty: 'pts/4',
    is_interactive: true,
    started_at: partial.started_at || iso(80),
    elapsed_sec: partial.elapsed_sec ?? 4800,
    project_name: {
      name: projectName,
      short_cwd: partial.short_cwd || cwd.replace('/data/zhouran/proj/', ''),
      git_root: partial.project_root || cwd,
      git_branch: partial.git_status_detail?.branch || partial.project_status?.branch || 'main',
    },
    project: projectName,
    project_root: partial.project_root || cwd,
    short_cwd: partial.short_cwd || cwd.replace('/data/zhouran/proj/', ''),
    session_title: partial.session_title || null,
    display_name: partial.display_name || partial.current_activity,
    status: partial.status,
    status_group: partial.status_group,
    status_dot: partial.status_dot,
    status_reason: partial.status_reason || partial.current_activity,
    current_activity: partial.current_activity,
    user_instruction: partial.user_instruction || `Work on ${partial.current_activity}`,
    instruction_source: 'demo',
    instruction_confidence: 0.9,
    instruction: { text: partial.user_instruction || partial.current_activity, source: 'demo', source_file: '', confidence: 0.9 },
    child_processes: partial.child_processes || [],
    active_commands: partial.active_commands || [],
    foreground: partial.foreground || {
      pid: rootPid,
      cmd: partial.root_cmd || `${partial.agent_type} demo`,
      tty: 'pts/4',
      is_interactive: true,
      waiting_input: partial.status_group === 'needs_input',
      alive: true,
      last_activity_ts: Math.floor((now - (partial.heartbeat_age_sec || 90) * 1000) / 1000),
      last_tool: 'edit',
      last_message_summary: partial.current_activity,
      status: partial.status,
    },
    background_jobs: partial.background_jobs || [],
    heartbeat_ts: Math.floor((now - (partial.heartbeat_age_sec || 90) * 1000) / 1000),
    heartbeat_age_sec: partial.heartbeat_age_sec ?? 90,
    recent_output: partial.recent_output || '',
    pending_items: partial.pending_items || [],
    last_user_message: partial.last_user_message || '',
    conversation: partial.conversation || [
      { role: 'user', text: partial.user_instruction || `Work on ${partial.current_activity}`, ts: Math.floor((now - 12 * 60_000) / 1000), source: 'demo' },
      { role: 'assistant', text: partial.recent_output || partial.current_activity, ts: Math.floor((now - 4 * 60_000) / 1000), source: 'demo' },
    ],
    source_file: 'demo',
    confidence: 0.9,
    cpu_percent: partial.cpu_percent ?? 4.2,
    memory_percent: partial.memory_percent ?? 2.1,
    project_status: partial.project_status || {
      dirty_files: partial.git_status_detail?.changed_files || [],
      has_uncommitted: (partial.git_status_detail?.dirty_count || 0) > 0,
      has_untracked: false,
      test_status: 'unknown',
      branch: partial.git_status_detail?.branch || 'main',
      recent_files: partial.recent_files || [],
    },
    git_status: partial.git_status || 'clean',
    git_status_detail: partial.git_status_detail || {
      branch: 'main',
      dirty_count: 0,
      changed_files: [],
      staged_count: 0,
      unstaged_count: 0,
      untracked_count: 0,
      is_repo: true,
      command_failed: false,
    },
    error_hints: partial.error_hints || [],
    recent_files: partial.recent_files || [],
    resource_usage: partial.resource_usage || { cpu_percent: 4.2, memory_percent: 2.1, rss_mb: 420, children_count: 1 },
    is_pinned: partial.is_pinned || false,
    is_ignored: partial.is_ignored || false,
    tags: partial.tags || [],
    timeline: partial.timeline || [],
    recent_logs: partial.recent_logs || [],
    source: partial.source || 'process',
    source_id: partial.source_id || `process:${rootPid}`,
    runtime_type: partial.runtime_type || (partial.agent_type && partial.agent_type !== 'unknown' ? 'agent' : 'unknown'),
    detected_app: partial.detected_app || partial.agent_type || 'unknown',
  }
}

